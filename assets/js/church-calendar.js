  /* --- Пост -------------------------------------------------------------- */

  // Порядок проверок важен: сплошная седмица сильнее многодневного поста,
  // строгий однодневный — сильнее обычной среды и пятницы.
  function fastFor(date, off) {
    var m = date.getUTCMonth() + 1;
    var d = date.getUTCDate();
    var dow = date.getUTCDay();
    var md = m * 100 + d;

    if (off >= -70 && off <= -64) return { level: 'solid', text: 'Сплошная седмица — поста нет' };
    if (off >= 0 && off <= 6) return { level: 'solid', text: 'Светлая седмица — поста нет' };
    if (off >= 50 && off <= 56) return { level: 'solid', text: 'Троицкая седмица — поста нет' };
    if (md >= 107 && md <= 117) return { level: 'solid', text: 'Святки — поста нет' };

    // Сырная седмица начинается в понедельник: в саму Неделю мясопустную
    // ещё заговляются на мясо
    if (off >= -55 && off <= -50) {
      return { level: 'cheese', text: 'Сырная седмица (Масленица): мясо не едят, среда и пятница не постные' };
    }

    if (off >= -48 && off <= -1) {
      return { level: 'strict', text: 'Великий пост' };
    }

    if (md === 118) return { level: 'strict', text: 'Строгий пост: Крещенский сочельник' };
    if (md === 911) return { level: 'strict', text: 'Строгий пост: Усекновение главы Иоанна Предтечи' };
    if (md === 927) return { level: 'strict', text: 'Строгий пост: Воздвижение Креста Господня' };
    if (md === 106) return { level: 'strict', text: 'Строгий пост: Рождественский сочельник' };

    if (off >= 57 && md <= 711) return { level: 'fast', text: 'Петров (Апостольский) пост' };
    if (md >= 814 && md <= 827) return { level: 'fast', text: 'Успенский пост' };
    if (md >= 1128 || md <= 106) return { level: 'fast', text: 'Рождественский пост' };

    if (dow === 3) return { level: 'fast', text: 'Постный день — среда' };
    if (dow === 5) return { level: 'fast', text: 'Постный день — пятница' };

    return { level: 'none', text: 'Поста нет' };
  }

  /* --- Седмица и глас ----------------------------------------------------- */

  function weekLabel(date, off, offPrev) {
    var dow = date.getUTCDay();
    var n;

    if (off >= -48 && off <= -7) {
      if (dow === 0) return 'Неделя ' + ((off + 49) / 7) + '-я Великого поста';
      return 'Седмица ' + (Math.floor((off + 48) / 7) + 1) + '-я Великого поста';
    }

    if (off >= -6 && off <= -1) return 'Страстная седмица';
    if (off >= 0 && off <= 6) return 'Светлая седмица';

    if (off >= 7 && off <= 48) {
      n = Math.floor(off / 7) + 1;
      return (dow === 0 ? 'Неделя ' : 'Седмица ') + n + '-я по Пасхе';
    }

    // Сама Пятидесятница считается ещё по Пасхе: счёт «по Пятидесятнице»
    // начинается со следующего дня
    if (off === 49) return 'Неделя 8-я по Пасхе';

    // Всё остальное считается от Пятидесятницы — своей или прошлогодней
    var base = off >= 49 ? off : offPrev;
    n = Math.floor((base - 49) / 7);
    if (dow === 0) return 'Неделя ' + n + '-я по Пятидесятнице';
    return 'Седмица ' + (n + 1) + '-я по Пятидесятнице';
  }

  // Глас поётся по кругу восьми, отсчёт — от Антипасхи. На Страстной и
  // Светлой седмицах гласа нет.
  function toneLabel(off, offPrev) {
    var base = off >= 7 ? off : (off <= -9 ? offPrev : null);
    if (base === null) return '';
    return 'глас ' + ((Math.floor((base - 7) / 7) % 8 + 8) % 8 + 1);
  }

  /* --- Сведения о дне ----------------------------------------------------- */

  function day(date) {
    var d = utc(date.getUTCFullYear(), date.getUTCMonth() + 1, date.getUTCDate());
    var year = d.getUTCFullYear();

    var p = pascha(year);
    var off = diffDays(d, p);
    // До Пасхи текущего года круг седмиц ведётся от прошлогодней
    var offPrev = diffDays(d, pascha(year - 1));

    var items = [];
    var rank = 0;

    var mv = MOVABLE[String(off)];
    if (mv) { items.push(mv.t); rank = Math.max(rank, mv.r || 0); }

    // Светлая седмица: дни без отдельной записи всё равно называются
    if (!mv && off >= 1 && off <= 6) items.push('Светлая седмица. ' + capitalize(WEEKDAYS[d.getUTCDay()]));

    var fx = FIXED[mdKey(d)];
    if (fx) {
      fx.i.forEach(function (t) { items.push(t); });
      rank = Math.max(rank, fx.r || 0);
    }

    var old = addDays(d, -styleShift(year));

    return {
      date: d,
      iso: iso(d),
      year: year,
      month: d.getUTCMonth() + 1,
      dayNum: d.getUTCDate(),
      monthName: MONTHS_GEN[d.getUTCMonth()],
      monthNom: MONTHS_NOM[d.getUTCMonth()],
      weekday: WEEKDAYS[d.getUTCDay()],
      weekdayShort: WEEKDAYS_SHORT[d.getUTCDay()],
      oldStyle: old.getUTCDate() + ' ' + MONTHS_GEN[old.getUTCMonth()],
      week: weekLabel(d, off, offPrev),
      tone: toneLabel(off, offPrev),
      title: items.length ? items[0] : '',
      items: items,
      rank: rank,
      fast: fastFor(d, off),
      source: 'https://azbyka.ru/days/' + iso(d)
    };
  }

  function capitalize(s) { return s.charAt(0).toUpperCase() + s.slice(1); }

  /* Ближайший великий или двунадесятый праздник после указанного дня.
     Дальше двух месяцев не ищем: столько всё равно не нужно, а перебор
     остаётся дешёвым. */
  function nextGreat(date, limit) {
    var d = date;
    var max = limit || 70;
    for (var i = 1; i <= max; i++) {
      var info = day(addDays(d, i));
      if (info.rank > 0) return info;
    }
    return null;
  }

  function month(year, m) {
    var out = [];
    var last = new Date(Date.UTC(year, m, 0)).getUTCDate();
    for (var i = 1; i <= last; i++) out.push(day(utc(year, m, i)));
    return out;
  }

  /* Сегодняшний день по местному времени, но в виде UTC-даты: так расчёт
     не съезжает на сутки в зависимости от часового пояса */
  function today() {
    var now = new Date();
    return utc(now.getFullYear(), now.getMonth() + 1, now.getDate());
  }

